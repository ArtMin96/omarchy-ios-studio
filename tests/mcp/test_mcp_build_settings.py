"""ios_project_build_settings end to end: the MCP server over stdio, the real helper, a throwaway project and a
fake xtool (IOS_STUDIO_XTOOL), with state in a temporary folder. View with suggestions, dry run, confirm,
ios_project_info, and a compile-only build whose prebuild regenerates the generated xtool.yml.

Needs the MCP server's dependencies (the dev venv; skipped otherwise):
    python -m pytest tests/mcp/test_mcp_build_settings.py
"""
from __future__ import annotations

import asyncio
import sys
import tempfile
import unittest
from pathlib import Path

from mcp.client.stdio import stdio_client

from mcp import ClientSession, StdioServerParameters
from support import ROOT, isolated_env, write_exe
from support.fakes import FAKE_XTOOL, GENERATE

RUN_SH = """\
#!/usr/bin/env bash
OPEN_FILES=4000
./generate.sh
export BUILD_FLAVOR=dev
ulimit -Sn "$OPEN_FILES"
exec xtool dev build
"""


class BuildSettingsTool(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="mcp-bs-"))
        self.env = isolated_env(self.tmp, xdg=("XDG_STATE_HOME", "XDG_CACHE_HOME", "XDG_CONFIG_HOME"))
        self.env["IOSSTUDIO_MCP_ALLOW_PATHS"] = str(self.tmp)
        self.env["IOSSTUDIO_RUNTIME_DIR"] = str(self.tmp / "rt")
        self.env["PYTHONPATH"] = str(ROOT / "mcp")
        self.env["IOS_STUDIO_XTOOL"] = str(write_exe(self.tmp / "xtool", FAKE_XTOOL))
        self.proj = self.tmp / "Gen"
        self.proj.mkdir()
        (self.proj / "Package.swift").write_text('// swift-tools-version: 6.0\nlet package = Package(name: "App")\n')
        (self.proj / "xtool.yml").write_text("# GENERATED by generate.sh\nversion: 1\nbundleID: com.example.old\n")
        for name, text in (("generate.sh", GENERATE), ("run.sh", RUN_SH)):
            (self.proj / name).write_text(text)
            (self.proj / name).chmod(0o755)

    def test_flow(self):
        asyncio.run(self._flow())

    async def _flow(self):
        params = StdioServerParameters(command=sys.executable, args=["-m", "iosstudio_mcp"], env=self.env,
                                       cwd=str(ROOT / "mcp"))
        async with stdio_client(params) as (r, w), ClientSession(r, w) as s:
            await s.initialize()

            async def call(name, **args):
                res = await s.call_tool(name, args)
                text = "".join(getattr(c, "text", "") for c in res.content)
                self.assertFalse(res.is_error, f"{name}: {text}")
                return res.structured_content or {}

            async def call_err(name, **args):
                res = await s.call_tool(name, args)
                self.assertTrue(res.is_error)
                return "".join(getattr(c, "text", "") for c in res.content)

            p = str(self.proj)
            add = await call("ios_project_add", project_path=p)
            self.assertTrue(add["project"]["generated"])
            info = await call("ios_project_info", project_path=p)
            sug = info["suggested_build_settings"]["settings"]
            self.assertEqual(sug, {"prebuild": "./generate.sh", "env": {"BUILD_FLAVOR": "dev"}, "openFiles": 4000,
                                   "allowGenerated": True})
            self.assertIn("ios_project_build_settings", " ".join(info["next_steps"]))

            # Refused while not allowed; the error names the new setting.
            b = await call("ios_build_start", project_path=p, action="compile")
            st = await self._wait(call, b["build_id"])
            self.assertEqual(st["state"], "failed")
            self.assertEqual(st["error"]["code"], "generated-project")
            self.assertNotIn("…", st["error"]["message"])
            self.assertIn("ios_project_build_settings", " ".join(st["next_steps"]))

            view = await call("ios_project_build_settings", project_path=p)
            self.assertFalse(view["done"])
            self.assertEqual(view["suggested"]["prebuild"], "./generate.sh")

            dry = await call("ios_project_build_settings", project_path=p, apply_suggested=True,
                             prebuild="./generate.sh 7", env={"EXTRA": "1"})
            self.assertFalse(dry["done"])
            self.assertIn("Dry run", dry["message"])
            self.assertEqual(len(dry["changes"]), 5, dry["changes"])   # suggested env merged with the explicit one
            self.assertEqual(dry["settings"]["env"], {"BUILD_FLAVOR": "dev", "EXTRA": "1"})
            self.assertNotIn("suggested", dry)                          # the dry run covers every suggestion
            self.assertNotIn("build_settings", await call("ios_project_info", project_path=p))   # nothing saved

            err = await call_err("ios_project_build_settings", project_path=p, prebuild="./a && ./b", confirm=True)
            self.assertIn("without a shell", err)

            done = await call("ios_project_build_settings", project_path=p, apply_suggested=True,
                              prebuild="./generate.sh 7", confirm=True)
            self.assertTrue(done["done"], done)
            self.assertEqual(done["settings"]["prebuild"], "./generate.sh 7")
            info = await call("ios_project_info", project_path=p)
            self.assertEqual(info["build_settings"]["env"], {"BUILD_FLAVOR": "dev"})
            self.assertNotIn("suggested_build_settings", info)

            b = await call("ios_build_start", project_path=p, action="compile")
            st = await self._wait(call, b["build_id"])
            self.assertEqual(st["state"], "succeeded", st)
            log = await call("ios_build_log", build_id=b["build_id"], grep="generate.sh|BUILD_FLAVOR|NOFILE|bundleID")
            text = "\n".join(str(x) for x in log.get("lines") or [])
            self.assertIn("args=7", text)
            self.assertIn("BUILD_FLAVOR=dev", text)
            self.assertIn("com.example.gen7", text)

            # A failing prebuild is one config diagnostic with a hint.
            await call("ios_project_build_settings", project_path=p, prebuild="./generate.sh fail", confirm=True)
            b = await call("ios_build_start", project_path=p, action="compile")
            st = await self._wait(call, b["build_id"])
            self.assertEqual(st["state"], "failed")
            diags = await call("ios_build_diagnostics", build_id=b["build_id"])
            (g,) = diags["diagnostics"]
            self.assertEqual(g["category"], "config")
            self.assertIn("prebuild", g["message"])
            self.assertTrue(g.get("hint"))

    async def _wait(self, call, build_id):
        for _ in range(20):
            st = await call("ios_build_status", build_id=build_id, wait_seconds=10)
            if st.get("state") in ("succeeded", "failed", "cancelled"):
                return st
        self.fail("build did not finish")


if __name__ == "__main__":
    unittest.main()
