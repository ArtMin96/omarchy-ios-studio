"""Build settings through bin/iosstudio-helper: compile-only builds with a fake xtool (IOS_STUDIO_XTOOL), a prebuild that
regenerates xtool.yml, env, the open-file limit, a failing prebuild as a `config` diagnostic."""
from __future__ import annotations

import json
import resource
import subprocess
import tempfile
import unittest
from pathlib import Path

from iosstudio.features import build_settings as B
from support import ROOT, isolated_env, write_exe
from support.fakes import FAKE_XTOOL, GENERATE

INF = resource.RLIM_INFINITY


def _low_soft_limit() -> None:
    """The helper starts with a soft open-file limit of 1024 (a login session's usual), so raising it shows."""
    _soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    resource.setrlimit(resource.RLIMIT_NOFILE, (min(1024, hard), hard))


class BuildPath(unittest.TestCase):
    """compile-only builds through bin/iosstudio-helper with IOS_STUDIO_XTOOL pointing at a fake xtool."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="bs-build-"))
        self.env = isolated_env(self.tmp)
        self.env["IOS_STUDIO_XTOOL"] = str(write_exe(self.tmp / "xtool", FAKE_XTOOL))
        self.proj = self.tmp / "App"
        self.proj.mkdir()
        (self.proj / "Package.swift").write_text('// swift-tools-version: 6.0\nlet package = Package(name: "App")\n')
        (self.proj / "xtool.yml").write_text("# GENERATED by generate.sh\nversion: 1\nbundleID: com.example.old\n")
        (self.proj / "generate.sh").write_text(GENERATE)
        (self.proj / "generate.sh").chmod(0o755)

    def helper(self, *args) -> tuple[int, list[dict]]:
        r = subprocess.run([str(ROOT / "bin" / "iosstudio-helper"), *args], env=self.env, capture_output=True,
                           text=True, timeout=60, stdin=subprocess.DEVNULL, preexec_fn=_low_soft_limit)
        events = [json.loads(ln) for ln in r.stdout.splitlines() if ln.startswith("{")]
        return r.returncode, events

    def settings(self, patch: dict, dry: bool = False) -> dict:
        args = ["projects", "build-settings", "--path", str(self.proj), "--set", json.dumps(patch)]
        rc, ev = self.helper(*args, *(["--dry-run"] if dry else []))
        self.assertEqual(rc, 0, ev)
        return ev[-1]["data"]

    def build(self) -> tuple[dict, list[dict]]:
        rc, ev = self.helper("build", "compile", "--path", str(self.proj))
        done = ev[-1]
        self.assertEqual(done["event"] if "event" in done else "done", "done", ev[-3:])
        return done, ev

    @staticmethod
    def logs(ev):
        return [e.get("text") or e.get("line") or e.get("message") or "" for e in ev if e.get("event") == "log"]

    def test_generated_project_is_refused_until_allowed(self):
        done, ev = self.build()
        self.assertFalse(done["ok"])
        self.assertEqual(done["error"]["code"], "generated-project")
        self.assertIn("Build settings", done["error"]["message"])
        self.assertEqual(done["error"]["fix"]["action"], "build-settings")

    def test_dry_run_saves_nothing(self):
        d = self.settings({"prebuild": "./generate.sh", "allowGenerated": True}, dry=True)
        self.assertFalse(d["saved"])
        self.assertEqual(len(d["changes"]), 2)
        rc, ev = self.helper("projects", "build-settings", "--path", str(self.proj))
        self.assertEqual(ev[-1]["data"]["settings"], B.empty())

    def test_prebuild_env_and_open_files_reach_the_build(self):
        soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
        want = min(hard, 4000)
        d = self.settings({"prebuild": "./generate.sh 2", "env": {"BUILD_FLAVOR": "dev"}, "openFiles": want,
                           "allowGenerated": True})
        self.assertTrue(d["saved"])
        rc, ev = self.helper("projects", "info", "--path", str(self.proj))
        self.assertEqual(ev[-1]["data"]["buildSettings"]["env"], {"BUILD_FLAVOR": "dev"})
        done, ev = self.build()
        self.assertTrue(done["ok"], done)
        text = "\n".join(self.logs(ev))
        self.assertIn("generate.sh: flavor=dev args=2", text)
        self.assertIn("BUILD_FLAVOR=dev", text)
        self.assertIn(f"NOFILE={want}", text)
        self.assertIn("bundleID: com.example.gen2", text)       # xtool saw the regenerated xtool.yml
        self.assertEqual(done["data"]["bundleId"], "com.example.gen2")
        steps = [(e["id"], e["state"]) for e in ev if e.get("event") == "step"]
        self.assertEqual(steps[0], ("prebuild", "pending"))
        self.assertIn(("prebuild", "done"), steps)
        self.assertEqual(resource.getrlimit(resource.RLIMIT_NOFILE)[0], soft)   # only the child's limit changed

    def test_failing_prebuild_is_a_config_diagnostic(self):
        self.settings({"prebuild": "./generate.sh fail", "allowGenerated": True})
        done, ev = self.build()
        self.assertFalse(done["ok"])
        self.assertEqual(done["error"]["code"], "prebuild-failed")
        diags = [e for e in ev if e.get("event") == "diagnostic"]
        self.assertEqual(len(diags), 1, diags)
        self.assertEqual(diags[0]["category"], "config")
        self.assertIn("not host-only", diags[0]["message"])
        self.assertTrue(diags[0].get("hint"))
        steps = {e["id"]: e["state"] for e in ev if e.get("event") == "step"}
        self.assertEqual(steps["prebuild"], "failed")
        self.assertFalse(any("fake xtool" in ln for ln in self.logs(ev)))     # xtool never ran

    def test_missing_prebuild_and_too_high_limit(self):
        self.settings({"prebuild": "./nope.sh", "allowGenerated": True})
        done, ev = self.build()
        self.assertEqual(done["error"]["code"], "prebuild-failed")
        self.assertIn("not found", done["error"]["message"])
        _soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
        if hard != INF and hard < B.MAX_OPEN_FILES:
            self.settings({"prebuild": "", "openFiles": hard + 1})
            done, ev = self.build()
            self.assertEqual(done["error"]["code"], "open-files-limit")
            self.assertIn(f"hard limit is {hard}", done["error"]["message"])
