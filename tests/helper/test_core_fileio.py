"""core/fileio, core/xtool_yml and core/jsonc: the shared file utilities.

- fileio.lock really excludes another process; atomic_write/replacing leave the old file or the new one, never a
  temp file; path_key is stable.
- xtool_yml reads every tests/fixtures/project-check fixture with line numbers, and set_key changes one line only.
- jsonc parses comments and trailing commas with spans, and reports errors with a line number.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from iosstudio.core import fileio, jsonc, xtool_yml
from support import ROOT

FIXTURES = ROOT / "tests/fixtures/project-check"
HELPER = ROOT / "helper"

_HOLDER = """
import sys, time
sys.path.insert(0, sys.argv[1])
from pathlib import Path
from iosstudio.core import fileio
with fileio.lock(Path(sys.argv[2])):
    print("locked", flush=True)
    sys.stdin.readline()
"""


class Lock(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.path = self.tmp / "sub" / "x.lock"

    def tearDown(self):
        import shutil
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_another_process_holding_it_blocks_us(self):
        p = subprocess.Popen([sys.executable, "-c", _HOLDER, str(HELPER), str(self.path)],
                             stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)
        try:
            self.assertEqual(p.stdout.readline().strip(), "locked")
            with self.assertRaises(BlockingIOError):
                with fileio.lock(self.path, blocking=False):
                    pass
            p.stdin.write("\n")
            p.stdin.flush()
            p.wait(timeout=10)
            with fileio.lock(self.path, blocking=False):   # free again once the holder exits
                pass
        finally:
            p.kill()
            p.wait(timeout=10)

    def test_never_truncates_the_lock_file(self):
        self.path.parent.mkdir(parents=True)
        self.path.write_text("1234 pid\n")
        with fileio.lock(self.path):
            pass
        self.assertEqual(self.path.read_text(), "1234 pid\n")

    def test_path_key(self):
        self.assertEqual(fileio.path_key("/a/App"), fileio.path_key(Path("/a/App")))
        self.assertNotEqual(fileio.path_key("/a/App"), fileio.path_key("/b/App"))
        self.assertEqual(len(fileio.path_key("/a")), 16)


class AtomicWrite(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())

    def tearDown(self):
        import shutil
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_text_and_bytes_with_mode(self):
        p = self.tmp / "d" / "f.txt"
        fileio.atomic_write(p, "héllo\n")
        self.assertEqual(p.read_text(), "héllo\n")
        self.assertEqual(p.stat().st_mode & 0o777, 0o644)
        fileio.atomic_write(p, b"\x00\x01", 0o600, fsync=True)
        self.assertEqual(p.read_bytes(), b"\x00\x01")
        self.assertEqual(p.stat().st_mode & 0o777, 0o600)
        self.assertEqual(os.listdir(p.parent), ["f.txt"])

    def test_a_failed_write_keeps_the_old_file_and_no_temp(self):
        p = self.tmp / "f.json"
        fileio.save_json(p, {"a": 1})
        with self.assertRaises(TypeError):
            fileio.atomic_write(p, 42)   # not str/bytes: the write fails
        self.assertEqual(fileio.load_json(p), {"a": 1})
        self.assertEqual(os.listdir(self.tmp), ["f.json"])

    def test_replacing_a_symlink(self):
        link = self.tmp / "link"
        for target in ("one", "two"):
            with fileio.replacing(link) as tmp:
                os.symlink(target, tmp)
        self.assertEqual(os.readlink(link), "two")
        self.assertEqual(os.listdir(self.tmp), ["link"])

    def test_load_json_default_on_bad_data(self):
        p = self.tmp / "bad.json"
        p.write_bytes(b"\xff\xfe{")
        self.assertEqual(fileio.load_json(p, {}), {})
        self.assertIsNone(fileio.load_json(self.tmp / "missing.json"))


class XtoolYml(unittest.TestCase):
    def test_every_fixture_parses_with_line_numbers(self):
        cases = sorted(d for d in FIXTURES.iterdir() if (d / "xtool.yml").is_file())
        self.assertGreater(len(cases), 5)
        for d in cases:
            text = (d / "xtool.yml").read_text()
            y = xtool_yml.read(d / "xtool.yml")
            lines = text.splitlines()
            for k in y.keys:
                self.assertTrue(lines[k.line - 1].startswith(k.name), (d.name, k))
            self.assertEqual(y.values.get("version"), "1", d.name)

    def test_scalars_quotes_comments_and_extensions(self):
        y = xtool_yml.parse("# GENERATED by gen.sh\nversion: 1\nbundleID: 'com.a.b' # id\nproduct: App  # c\n"
                            "iconPath:\nskipLSP: yes\nextensions:\n  - product: W\n    infoPath: W.plist\n"
                            "  - product: X\n")
        self.assertTrue(y.generated)
        self.assertEqual(y.values["bundleID"], "com.a.b")
        self.assertEqual(y.get("product"), "App")
        self.assertIsNone(y.get("iconPath"))
        self.assertEqual(y.lines["product"], 4)
        self.assertTrue(y.flag("skipLSP"))
        self.assertFalse(y.flag("missing"))
        self.assertEqual(y.extensions, [[("product", 8), ("infoPath", 9)], [("product", 10)]])

    def test_missing_file_is_empty(self):
        y = xtool_yml.read(Path("/nonexistent/xtool.yml"))
        self.assertEqual((y.keys, y.generated), ([], False))

    def test_set_key_round_trip(self):
        for d in sorted(FIXTURES.iterdir()):
            f = d / "xtool.yml"
            if not f.is_file():
                continue
            text = f.read_text()
            new = xtool_yml.set_key(text, "bundleID", "com.test.Round")
            self.assertEqual(xtool_yml.parse(new).values["bundleID"], "com.test.Round", d.name)
            old_lines = [ln for ln in text.splitlines() if not ln.startswith("bundleID")]
            self.assertEqual([ln for ln in new.splitlines() if not ln.startswith("bundleID")], old_lines, d.name)
            self.assertEqual(xtool_yml.set_key(new, "bundleID", "com.test.Round"), new)

    def test_set_key_keeps_a_trailing_comment(self):
        self.assertEqual(xtool_yml.set_key("version: 1\nbundleID: a.b # mine\n", "bundleID", "c.d"),
                         "version: 1\nbundleID: c.d # mine\n")
        self.assertEqual(xtool_yml.set_key("version: 1", "bundleID", "c.d"), "version: 1\nbundleID: c.d\n")


class Jsonc(unittest.TestCase):
    TEXT = '﻿// top\n{\n  "a": 1, /* x */\n  "b": [1, 2,],\n  "c": {"d": "e // not a comment"},\n}\n'

    def test_value_and_spans(self):
        root = jsonc.parse(self.TEXT)
        self.assertEqual(root.value, {"a": 1, "b": [1, 2], "c": {"d": "e // not a comment"}})
        self.assertEqual([m.key for m in root.members], ["a", "b", "c"])
        a, b, c = root.members
        self.assertEqual(self.TEXT[a.kstart:a.node.end], '"a": 1')
        self.assertEqual(self.TEXT[a.comma], ",")
        self.assertGreaterEqual(c.comma, 0)                 # the trailing comma before }
        self.assertGreaterEqual(b.node.items[-1].comma, 0)  # and before ]
        self.assertEqual(self.TEXT[root.start], "{")
        self.assertEqual(jsonc.skip(self.TEXT, 0), root.start)

    def test_load_and_plain_json(self):
        self.assertEqual(jsonc.load("  \n"), {})
        doc = {"x": [1.5, None, True, "s"], "y": {}}
        self.assertEqual(jsonc.load(json.dumps(doc, indent=2)), doc)

    def test_errors_name_the_line(self):
        for text, what in (('{\n"a": 1\n"b": 2}', "line 3"), ('{"a": 1 /* never ends', "never ends"),
                           ("{}\n{}", "extra text"), ("[" * 100 + "]" * 100, "nested too deeply"),
                           ('{"a": tru}', "unexpected"), ('{"a": "x\ny"}', "bad string")):
            with self.assertRaises(jsonc.JsoncError) as cm:
                jsonc.parse(text)
            self.assertIn(what, str(cm.exception), text)


