def test_project_info(tmp_path, state):
    p = project_with_files(tmp_path / "App", {"Package.swift": PACKAGE, "Resources/icon.png": "png",
                                              "xtool.yml": "version: 1\nbundleID: com.example.hello\n"
                                                           "iconPath: Resources/icon.png\n"})
    (p / "xtool").mkdir()
    (p / "xtool" / "Hello.ipa").write_text("")
    with store.edit_state() as st:
        st["added"].append(str(p))
        st["meta"][str(p)] = {"autoRenew": True}
    store.append_history({"path": str(p), "kind": "compile", "result": "ok", "duration": 3})
    info = model.project_info(p)
    assert info["name"] == info["product"] == "Hello" and info["package"] == "Pkg"
    assert info["bundleId"] == "com.example.hello" and info["iosMin"] == "18"
    assert info["icon"] == str((p / "Resources/icon.png").resolve())
    assert info["added"] and info["autoRenew"] and info["lastBuild"]["duration"] == 3
    assert info["ipa"] == str(p / "xtool" / "Hello.ipa") and info["signing"] is None
    assert info["runPresets"] == [] and info["runPreset"] is None and not info["generated"] and "note" not in info


