def test_renew_due_installs_over_wifi_and_records(state, tmp_path, monkeypatch, capsys):
    paths = setup_renew(state, tmp_path, {"Soon": (True, "U1", 1)})
    notes, asked = [], []
    monkeypatch.setattr(renew, "_notify", lambda *a: notes.append(a))
    monkeypatch.setattr(renew.build, "do_build", lambda flags, kind, interactive: (
        0, {"needsInstall": True, "ipa": "/x.ipa", "bundleId": "com.x", "profile": {"expires": 99.0}}, None))
    monkeypatch.setattr(renew, "_deviced_once",
                        lambda cmd, args, timeout=300: asked.append((cmd, args, timeout)) or {"ok": True})
    assert renew.renew_due(2, dry=False) == 0
    # as long as the Run button gives an install: ending the --once process now cancels it in the daemon
    assert asked == [("app.install", {"udid": "U1", "path": "/x.ipa"}, 600)]
    assert store.load_renewals()[paths["Soon"]]["via"] == "wifi"
    assert events(capsys)[-1]["data"]["renewed"] == [paths["Soon"]]
    assert notes and notes[0][0] == "Apps renewed" and notes[0][2] == "low"
    # an unreachable phone is a "try later"
    monkeypatch.setattr(renew, "_deviced_once", lambda cmd, args, timeout=300: None)
    assert renew.renew_due(2, dry=False) == renew.EXIT_TEMP


def test_units_and_timer_dry_runs(tmp_path, monkeypatch):
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "cfg"))
    svc, tmr = renew.unit_paths()
    assert svc == tmp_path / "cfg/systemd/user/ios-studio-renew.service" and tmr.name == "ios-studio-renew.timer"
    service, timer = renew.unit_texts()
    assert "projects renew-due --background" in service and "RestartPreventExitStatus=78" in service
    assert "OnCalendar=" in timer and "WantedBy=timers.target" in timer
    monkeypatch.setattr(renew, "systemctl", lambda *a: pytest.fail("dry run ran systemctl"))
    on = renew.enable_timer(dry=True)
    assert on["dryRun"] and on["actions"][-1] == "systemctl --user enable --now ios-studio-renew.timer"
    assert not svc.exists()
    off = renew.disable_timer(dry=True)
    assert off["actions"][0].startswith("systemctl --user disable --now")


def test_deviced_once_parses_the_reply(tmp_path, monkeypatch):
    repo = tmp_path / "repo"
    exe = repo / "bin" / "iosstudio-deviced"
    exe.parent.mkdir(parents=True)
    exe.write_text('#!/bin/sh\necho \'{"event":"log"}\'\nprintf \'{"ok": true, "data": {"a": "%s"}}\\n\' "$1"\necho junk\n')
    exe.chmod(0o755)
    monkeypatch.setattr(renew.appdirs, "REPO", repo)
    assert renew._deviced_once("app.install", {}) == {"ok": True, "data": {"a": "--once"}}
    exe.write_text("#!/bin/sh\necho nothing useful\n")
    assert renew._deviced_once("app.install", {}) is None
    monkeypatch.setattr(renew.appdirs, "REPO", tmp_path / "none")
    assert renew._deviced_once("app.install", {}) is None


