def mobileprovision(expires: datetime) -> bytes:
    pl = plistlib.dumps({"ExpirationDate": expires, "CreationDate": datetime(2026, 1, 1), "Name": "XTL",
                         "UUID": "U-1", "TeamIdentifier": ["TEAM"], "ProvisionedDevices": ["D1"],
                         "Entitlements": {"application-identifier": "TEAM.com.x"}})
    return b"\x30\x82CMS-junk" + pl + b"\x00trailer"


def test_read_profile_from_ipa_and_app(tmp_path):
    exp = datetime(2027, 3, 1, 12, 0)
    want = datetime(2027, 3, 1, 12, 0, tzinfo=timezone.utc).timestamp()
    ipa = tmp_path / "A.ipa"
    with zipfile.ZipFile(ipa, "w") as z:
        z.writestr("Payload/A.app/Frameworks/X.framework/embedded.mobileprovision", b"nested, not ours")
        z.writestr("Payload/A.app/embedded.mobileprovision", mobileprovision(exp))
    p = store.read_profile(str(ipa))
    assert p["expires"] == want and p["team"] == "TEAM" and p["appId"] == "TEAM.com.x" and p["devices"] == ["D1"]
    app = tmp_path / "A.app"
    app.mkdir()
    (app / "embedded.mobileprovision").write_bytes(mobileprovision(exp))
    assert store.read_profile(str(app))["uuid"] == "U-1"
    assert store.read_profile(None) is None and store.read_profile(str(tmp_path / "none.ipa")) is None
    (tmp_path / "bad.ipa").write_text("not a zip")
    assert store.read_profile(str(tmp_path / "bad.ipa")) is None
    assert store.profile_from_bytes(b"no plist here") is None
    assert store.profile_from_bytes(b"<?xml broken </plist>") is None


