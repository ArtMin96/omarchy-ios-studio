def test_history_last_build_and_estimate(state, monkeypatch):
    monkeypatch.setattr(store, "MAX_HISTORY", 8)
    for d in (10, 20, 30, 40, 50, 60):
        store.append_history({"path": "/a", "kind": "run", "result": "ok", "duration": d})
    store.append_history({"path": "/a", "kind": "run", "result": "failed", "duration": 1})
    store.append_history({"path": "/b", "kind": "run", "result": "ok", "duration": 5})
    store.append_history({"path": "/a", "kind": "compile", "result": "ok", "duration": 2})
    h = store.load_history()
    assert len(h) == 8 and h[0]["duration"] == 20                      # trimmed to MAX_HISTORY
    assert store.last_build("/a")["kind"] == "compile" and store.last_build("/zzz") is None
    assert store.estimate_duration("/a", "run") == 40                  # median of the last five ok runs
    assert store.estimate_duration("/a", "install") is None


