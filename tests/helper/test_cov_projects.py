def test_norm_and_require_path(tmp_path):
    real = tmp_path / "real"
    real.mkdir()
    (tmp_path / "link").symlink_to(real)
    assert model.norm_path(tmp_path / "link") == str(real.resolve())
    assert model.require_path({"path": str(tmp_path / "link")}) == real.resolve()
    with pytest.raises(HelperError) as ei:
        model.require_path({"path": True})
    assert ei.value.code == "usage"
    with pytest.raises(HelperError) as ei:
        model.require_path({"path": str(tmp_path / "gone")})
    assert ei.value.code == "not-found" and ei.value.fix["path"] == str((tmp_path / "gone").resolve())
    with pytest.raises(HelperError) as ei:
        model.require_project({"path": str(real)})
    assert ei.value.code == "not-a-project"


def test_package_info(tmp_path):
    (tmp_path / "Package.swift").write_text(PACKAGE)
    assert model.package_info(tmp_path / "Package.swift") == {
        "package": "Pkg", "libraries": ["Hello"], "iosMin": "18", "toolsVersion": "6.1"}
    (tmp_path / "Package.swift").write_text('platforms: [.iOS("17.0")]')
    info = model.package_info(tmp_path / "Package.swift")
    assert info["package"] == tmp_path.name and info["iosMin"] == "17" and info["toolsVersion"] is None
    assert model.package_info(tmp_path / "missing.swift") == {}


