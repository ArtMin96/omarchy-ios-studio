def setup_renew(state, tmp_path, entries: dict) -> dict:
    """entries: name -> (autoRenew, udid, days left or None). Creates the project folders."""
    paths = {}
    with store.edit_state() as st:
        for name, (auto, udid, _left) in entries.items():
            p = tmp_path / name
            p.mkdir()
            paths[name] = str(p)
            st["meta"][str(p)] = {"autoRenew": auto}
    ren = {paths[n]: {"udid": u, "expires": time.time() + left * 86400}
           for n, (_a, u, left) in entries.items() if left is not None}
    store.RENEWALS_FILE.write_text(json.dumps(ren))
    return paths


def test_due_projects(state, tmp_path):
    paths = setup_renew(state, tmp_path, {"Soon": (True, "U1", 1), "Later": (True, "U1", 5),
                                          "NoPhone": (True, None, 0.5), "Off": (False, "U1", 0.1)})
    with store.edit_state() as st:
        st["meta"][paths["NoPhone"]] = {"autoRenew": True}
        st["meta"]["/gone"] = {"autoRenew": True, "udid": "U2"}
    due = {Path(d["path"]).name: d for d in renew.due_projects(2)}
    assert set(due) == {"Soon", "Later", "NoPhone", "gone"}
    assert due["Soon"]["due"] and not due["Later"]["due"] and not due["NoPhone"]["due"]
    assert due["gone"]["due"] and not due["gone"]["exists"] and due["gone"]["daysLeft"] is None


