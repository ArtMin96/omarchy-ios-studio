def test_scan_finds_projects_and_convertible_packages(tmp_path, monkeypatch):
    root = tmp_path / "Code"
    project_with_files(root / "a" / "App1", {})
    project_with_files(root / "App1" / "Nested", {})                 # never descended into: App1 is a project
    project_with_files(root / "node_modules" / "Skip", {})
    project_with_files(root / ".hidden" / "Skip", {})
    conv = root / "Conv"
    (conv / "Sources" / "Hello").mkdir(parents=True)
    (conv / "Package.swift").write_text(PACKAGE)
    (conv / "Sources" / "Hello" / "App.swift").write_text("import SwiftUI\n@main struct HelloApp: App {}\n")
    project_with_files(root / "x" / "y" / "z" / "w" / "v" / "TooDeep", {})
    (root / "loop").symlink_to(root)
    project_with_files(root / "App1", {})
    monkeypatch.setattr(model, "roots", lambda: [root])
    monkeypatch.setattr(model.appdirs, "settings", lambda: {"projectScanDepth": 3})
    found, conv_list = model.scan()
    assert sorted(p.name for p in found) == ["App1", "App1"]
    assert {str(p.parent.name) for p in found} == {"a", "Code"}
    assert [c["name"] for c in conv_list] == ["Hello"] and conv_list[0]["reason"].startswith("SwiftUI")


