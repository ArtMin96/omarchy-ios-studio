class Validation(unittest.TestCase):
    def test_patch_merges_env_and_clears(self):
        before = B.apply_patch(B.empty(), {"prebuild": " ./generate.sh ", "env": {"A": "1", "B": 2},
                                           "openFiles": "65536", "allowGenerated": "true"})
        self.assertEqual(before, {"prebuild": "./generate.sh", "env": {"A": "1", "B": "2"}, "openFiles": 65536,
                                  "allowGenerated": True})
        after = B.apply_patch(before, {"env": {"A": None, "C": "x y"}, "prebuild": "", "openFiles": 0})
        self.assertEqual(after["env"], {"B": "2", "C": "x y"})
        self.assertIsNone(after["prebuild"])
        self.assertIsNone(after["openFiles"])
        self.assertTrue(after["allowGenerated"])
        self.assertEqual(B.apply_patch(before, {"env": {"Z": "1"}, "envReplace": True})["env"], {"Z": "1"})

    def test_invalid_values(self):
        for patch in ({"env": {"1BAD": "x"}}, {"env": {"A-B": "x"}}, {"env": {"A": ["x"]}},
                      {"openFiles": 10}, {"openFiles": "lots"}, {"prebuild": "./a.sh && ./b.sh"},
                      {"prebuild": "echo 'unterminated"}, {"prebuild": "a\nb"}, {"bogus": 1}):
            with self.subTest(patch=patch), self.assertRaises(B.Invalid):
                B.apply_patch(B.empty(), patch)

    def test_stored_only_keeps_set_keys_and_current_reads_it_back(self):
        s = B.apply_patch(B.empty(), {"env": {"A": "1"}})
        self.assertEqual(B.stored(s), {"env": {"A": "1"}})
        self.assertEqual(B.current({"build": B.stored(s)}), s)
        self.assertEqual(B.current({}), B.empty())
        self.assertEqual(B.current({"build": {"openFiles": True, "env": "x", "allowGenerated": "yes"}}), B.empty())

    def test_diff_lines(self):
        a = B.apply_patch(B.empty(), {"prebuild": "./g.sh", "env": {"A": "1", "B": "2"}})
        b = B.apply_patch(a, {"prebuild": "./g.sh dev", "env": {"A": None, "B": "3", "C": "4"}, "openFiles": 4096,
                              "allowGenerated": True})
        d = B.diff(a, b)
        self.assertEqual(len(d), 6, d)
        self.assertIn("Environment: remove A", d)
        self.assertIn("Environment: set C=4", d)
        self.assertEqual(B.diff(b, b), [])

    def test_prebuild_is_an_argv(self):
        self.assertEqual(B.prebuild_argv("./generate.sh 'http://a b' $HOME"), ["./generate.sh", "http://a b", "$HOME"])


class OpenFiles(unittest.TestCase):
    def test_default_raises_to_65536_capped(self):
        self.assertEqual(B.nofile_target(None, 1024, 524288), (65536, None))
        self.assertEqual(B.nofile_target(None, 1024, 4096), (4096, None))
        self.assertEqual(B.nofile_target(None, 100000, 524288), (None, None))
        self.assertEqual(B.nofile_target(None, INF, INF), (None, None))

    def test_explicit_value_and_hard_limit(self):
        self.assertEqual(B.nofile_target(200000, 1024, INF), (200000, None))
        self.assertEqual(B.nofile_target(65536, 70000, 524288), (None, None))
        target, err = B.nofile_target(1 << 20, 1024, 524288)
        self.assertIsNone(target)
        self.assertIn("hard limit is 524288", err)


class Suggestions(unittest.TestCase):
    def setUp(self):
        self.dir = Path(tempfile.mkdtemp(prefix="bs-suggest-"))

    def write(self, name, text, mode=0o644):
        f = self.dir / name
        f.write_text(textwrap.dedent(text))
        f.chmod(mode)

    def test_run_sh_like_garderi(self):
        self.write("xtool.yml", "# GENERATED by apps/ios/x/generate.sh for Dev. Never edit.\nversion: 1\nbundleID: a.b\n")
        self.write("generate.sh", "#!/bin/sh\n", 0o755)
        self.write("run.sh", """\
            #!/usr/bin/env bash
            # run.sh: runs generate.sh, exports FOO=bar in comments only
            OPEN_FILES=65536
            "$ADAPTER_DIR/generate.sh"
            export GARDERI_IOS_CROSS=1
            export DYNAMIC="$(date)"
            export PATH="/x:$PATH"
            if [[ "$(ulimit -Sn)" -lt "$OPEN_FILES" ]]; then
              ulimit -Sn "$OPEN_FILES" || exit 1
            fi
            exec xtool dev "$cmd"
            """)
        s = B.suggest(self.dir)
        self.assertEqual(s["settings"], {"prebuild": "./generate.sh", "env": {"GARDERI_IOS_CROSS": "1"},
                                         "openFiles": 65536, "allowGenerated": True})
        # Settings that already match aren't suggested again.
        have = B.apply_patch(B.empty(), s["settings"])
        self.assertIsNone(B.suggest(self.dir, have))

    def test_plain_project_has_none(self):
        self.write("xtool.yml", "version: 1\nbundleID: a.b\n")
        self.assertIsNone(B.suggest(self.dir))
        self.write("build.sh", "ulimit -n 8192\nexport 'X'=1\n")
        self.assertEqual(B.suggest(self.dir)["settings"], {"openFiles": 8192})


# ---------------------------------------------------------------- real builds through a fake xtool

FAKE_XTOOL = """\
#!/usr/bin/env python3
import os, resource, sys
print("fake xtool", " ".join(sys.argv[1:]))
print("BUILD_FLAVOR=" + os.environ.get("BUILD_FLAVOR", "<unset>"))
print("NOFILE=%d" % resource.getrlimit(resource.RLIMIT_NOFILE)[0])
print("YML=" + open("xtool.yml").read().splitlines()[2])
print("Building for debugging...")
print("[1/2] Compiling App App.swift")
print("Build complete! (0.1 secs)")
"""

GENERATE = """\
#!/bin/sh
echo "generate.sh: flavor=$BUILD_FLAVOR args=$*"
[ "$1" = fail ] && { echo "generate.sh: API_BASE_URL 'x' is not host-only" >&2; exit 3; }
printf '# GENERATED by generate.sh\\nversion: 1\\nbundleID: com.example.gen%s\\nproduct: App\\n' "$1" > xtool.yml
"""


def _low_soft_limit() -> None:
    """The helper starts with a soft open-file limit of 1024 (a login session's usual), so raising it shows."""
    _soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    resource.setrlimit(resource.RLIMIT_NOFILE, (min(1024, hard), hard))


class BuildPath(unittest.TestCase):
    """compile-only builds through bin/iosstudio-helper with IOS_STUDIO_XTOOL pointing at a fake xtool."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="bs-build-"))
        self.env = dict(os.environ)
        for var in ("XDG_STATE_HOME", "XDG_CACHE_HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME"):
            self.env[var] = str(self.tmp / var.lower())
        self.env.pop("IOSSTUDIO_DEMO", None)
        xtool = self.tmp / "xtool"
        xtool.write_text(FAKE_XTOOL)
        xtool.chmod(0o755)
        self.env["IOS_STUDIO_XTOOL"] = str(xtool)
        self.proj = self.tmp / "App"
        self.proj.mkdir()
        (self.proj / "Package.swift").write_text('// swift-tools-version: 6.0\nlet package = Package(name: "App")\n')
        (self.proj / "xtool.yml").write_text("# GENERATED by generate.sh\nversion: 1\nbundleID: com.example.old\n")
        (self.proj / "generate.sh").write_text(GENERATE)
        (self.proj / "generate.sh").chmod(0o755)

    def helper(self, *args) -> tuple[int, list[dict]]:
        r = subprocess.run([str(ROOT / "bin" / "iosstudio-helper"), *args], env=self.env, capture_output=True,
                           text=True, timeout=60, stdin=subprocess.DEVNULL, preexec_fn=_low_soft_limit)
        events = [json.loads(ln) for ln in r.stdout.splitlines() if ln.startswith("{")]
        return r.returncode, events

    def settings(self, patch: dict, dry: bool = False) -> dict:
        args = ["projects", "build-settings", "--path", str(self.proj), "--set", json.dumps(patch)]
        rc, ev = self.helper(*args, *(["--dry-run"] if dry else []))
        self.assertEqual(rc, 0, ev)
        return ev[-1]["data"]

    def build(self) -> tuple[dict, list[dict]]:
        rc, ev = self.helper("build", "compile", "--path", str(self.proj))
        done = ev[-1]
        self.assertEqual(done["event"] if "event" in done else "done", "done", ev[-3:])
        return done, ev

    @staticmethod
    def logs(ev):
        return [e.get("text") or e.get("line") or e.get("message") or "" for e in ev if e.get("event") == "log"]

    def test_generated_project_is_refused_until_allowed(self):
        done, ev = self.build()
        self.assertFalse(done["ok"])
        self.assertEqual(done["error"]["code"], "generated-project")
        self.assertIn("Build settings", done["error"]["message"])
        self.assertEqual(done["error"]["fix"]["action"], "build-settings")

    def test_dry_run_saves_nothing(self):
        d = self.settings({"prebuild": "./generate.sh", "allowGenerated": True}, dry=True)
        self.assertFalse(d["saved"])
        self.assertEqual(len(d["changes"]), 2)
        rc, ev = self.helper("projects", "build-settings", "--path", str(self.proj))
        self.assertEqual(ev[-1]["data"]["settings"], B.empty())

    def test_prebuild_env_and_open_files_reach_the_build(self):
        soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
        want = min(hard, 4000)
        d = self.settings({"prebuild": "./generate.sh 2", "env": {"BUILD_FLAVOR": "dev"}, "openFiles": want,
                           "allowGenerated": True})
        self.assertTrue(d["saved"])
        rc, ev = self.helper("projects", "info", "--path", str(self.proj))
        self.assertEqual(ev[-1]["data"]["buildSettings"]["env"], {"BUILD_FLAVOR": "dev"})
        done, ev = self.build()
        self.assertTrue(done["ok"], done)
        text = "\n".join(self.logs(ev))
        self.assertIn("generate.sh: flavor=dev args=2", text)
        self.assertIn("BUILD_FLAVOR=dev", text)
        self.assertIn(f"NOFILE={want}", text)
        self.assertIn("bundleID: com.example.gen2", text)       # xtool saw the regenerated xtool.yml
        self.assertEqual(done["data"]["bundleId"], "com.example.gen2")
        steps = [(e["id"], e["state"]) for e in ev if e.get("event") == "step"]
        self.assertEqual(steps[0], ("prebuild", "pending"))
        self.assertIn(("prebuild", "done"), steps)
        self.assertEqual(resource.getrlimit(resource.RLIMIT_NOFILE)[0], soft)   # only the child's limit changed

    def test_failing_prebuild_is_a_config_diagnostic(self):
        self.settings({"prebuild": "./generate.sh fail", "allowGenerated": True})
        done, ev = self.build()
        self.assertFalse(done["ok"])
        self.assertEqual(done["error"]["code"], "prebuild-failed")
        diags = [e for e in ev if e.get("event") == "diagnostic"]
        self.assertEqual(len(diags), 1, diags)
        self.assertEqual(diags[0]["category"], "config")
        self.assertIn("not host-only", diags[0]["message"])
        self.assertTrue(diags[0].get("hint"))
        steps = {e["id"]: e["state"] for e in ev if e.get("event") == "step"}
        self.assertEqual(steps["prebuild"], "failed")
        self.assertFalse(any("fake xtool" in ln for ln in self.logs(ev)))     # xtool never ran

    def test_missing_prebuild_and_too_high_limit(self):
        self.settings({"prebuild": "./nope.sh", "allowGenerated": True})
        done, ev = self.build()
        self.assertEqual(done["error"]["code"], "prebuild-failed")
        self.assertIn("not found", done["error"]["message"])
        _soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
        if hard != INF and hard < B.MAX_OPEN_FILES:
            self.settings({"prebuild": "", "openFiles": hard + 1})
            done, ev = self.build()
            self.assertEqual(done["error"]["code"], "open-files-limit")
            self.assertIn(f"hard limit is {hard}", done["error"]["message"])


