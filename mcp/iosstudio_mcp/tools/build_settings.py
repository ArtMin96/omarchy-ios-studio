"""Per-project build settings: ios_project_build_settings views and changes a project's prebuild command,
extra environment variables, open-file limit and whether a generated xtool.yml may be built (stored by the
helper in projects.json; see helper/build_settings.py)."""
from __future__ import annotations

import json
from typing import Annotated

from mcp.server.mcpserver import Context, MCPServer
from pydantic import Field

from .. import helper
from ..models import Out
from ..state import get_state, resolve_project
from . import ann, tool
from .projects import ProjectPath


class BuildSettings(Out):
    prebuild: str | None = Field(None, description="Command run in the project folder before each build "
                                                   "(split like a shell would, but run without a shell)")
    env: dict[str, str] = Field(default_factory=dict, description="Extra environment for the prebuild and xtool")
    open_files: int | None = Field(None, description="Soft open-file limit raised to before building "
                                                     "(default: 65536, capped at the hard limit)")
    allow_generated: bool = Field(False, description="Build even though xtool.yml says it's GENERATED")

    @classmethod
    def from_helper(cls, s: dict | None) -> "BuildSettings":
        s = s or {}
        return cls(prebuild=s.get("prebuild"), env=dict(s.get("env") or {}), open_files=s.get("openFiles"),
                   allow_generated=bool(s.get("allowGenerated")))


class BuildSettingsResult(Out):
    done: bool = Field(description="True when the settings were saved; false for a view or a dry run")
    message: str
    project: str
    path: str
    settings: BuildSettings = Field(description="The settings in effect; for a dry run, what confirm=true would save")
    changes: list[str] = Field(default_factory=list, description="What changed, or would change on confirm=true")
    suggested: BuildSettings | None = Field(None, description="Settings the project's own scripts imply that "
                                                              "aren't set yet (never applied by themselves)")
    suggested_reasons: list[str] = Field(default_factory=list)
    open_files_error: str | None = Field(None, description="Why the open-file limit can't be applied here")
    next_steps: list[str] = Field(default_factory=list)


def _suggested(data: dict) -> tuple[BuildSettings | None, list[str]]:
    sug = data.get("suggested") or {}
    if not sug.get("settings"):
        return None, []
    return BuildSettings.from_helper(sug["settings"]), list(sug.get("reasons") or [])[:12]


def register(mcp: MCPServer) -> None:

    @tool(mcp, annotations=ann("Project build settings", read_only=False, idempotent=True))
    async def ios_project_build_settings(
        ctx: Context,
        project_path: ProjectPath,
        prebuild: Annotated[str | None, Field(description="Command to run in the project folder before each build, "
                                                          "e.g. './generate.sh'. Split into arguments like a shell "
                                                          "would but run WITHOUT a shell (no |, &&, $VAR). '' removes "
                                                          "it")] = None,
        env: Annotated[dict[str, str | None] | None, Field(description="Environment variables to set for the "
                                                                       "prebuild and xtool, merged into the current "
                                                                       "ones; a null value removes that name, e.g. "
                                                                       "{'GARDERI_IOS_CROSS': '1', 'OLD': null}")] = None,
        open_files: Annotated[int | None, Field(ge=0, le=1 << 24, description="Soft open-file limit to raise to "
                                                                              "before building (0 = default)")] = None,
        allow_generated: Annotated[bool | None, Field(description="Build the project even though its xtool.yml is "
                                                                  "generated by its own scripts (set the prebuild "
                                                                  "that regenerates it too)")] = None,
        apply_suggested: Annotated[bool, Field(description="Start from the settings suggested by the project's own "
                                                           "scripts (run.sh, generate.sh); explicit arguments win")] = False,
        confirm: Annotated[bool, Field(description="false = dry run showing the changes. true only after the user "
                                                   "agreed")] = False,
    ) -> BuildSettingsResult:
        """View or change a project's build settings: a prebuild command run before each build (e.g. the
        script that regenerates a generated xtool.yml), extra environment variables, the open-file limit,
        and whether a generated project may be built. With no change arguments it shows the current
        settings and what the project's own scripts suggest. A change is a dry run listing the changes
        until confirm=true; ask the user first, because the prebuild command runs on their computer before
        every build (including automatic re-signing)."""
        state = get_state(ctx)
        p = await resolve_project(state, project_path)
        patch: dict = {}
        if prebuild is not None:
            patch["prebuild"] = prebuild
        if env is not None:
            patch["env"] = env
        if open_files is not None:
            patch["openFiles"] = open_files
        if allow_generated is not None:
            patch["allowGenerated"] = allow_generated
        changing = bool(patch) or apply_suggested
        flags: dict = {"path": p["path"]}
        if changing:
            flags["set"] = json.dumps(patch)
            flags["suggested"] = apply_suggested or None
            flags["dry_run"] = not confirm or None
        data = await helper.call("projects", "build-settings", flags)
        if isinstance(data, dict) and data.get("demo") is True:
            return BuildSettingsResult(done=False, message="Demo mode: build settings are never saved.",
                                       project=str(p.get("name") or ""), path=str(p.get("path") or ""),
                                       settings=BuildSettings.from_helper(data.get("settings")))
        name = p.get("name") or p["path"]
        sug, reasons = _suggested(data)
        changes = list(data.get("changes") or [])
        nxt: list[str] = []
        if not changing:
            done, msg = False, f"Build settings of {name}."
            if sug:
                nxt.append("The project's own scripts suggest settings that aren't set (see `suggested`). Ask the "
                           "user, then call with apply_suggested=true (dry run first).")
        elif not changes:
            done, msg = False, "Nothing to change: the settings already match."
        elif not confirm:
            done, msg = False, ("Dry run: these build settings would change. Nothing was saved. Ask the user to "
                                "confirm, then call again with the same arguments and confirm=true.")
        else:
            done, msg = True, f"Saved {len(changes)} change{'s' if len(changes) != 1 else ''} to {name}'s build settings."
            state.invalidate_projects()
            nxt.append(f"Build with ios_run(project_path='{p['path']}') or ios_build_start; the prebuild runs as "
                       "the first step and its output is in ios_build_log.")
        if data.get("openFilesError"):
            nxt.append("The open-file limit can't be applied in this session (see open_files_error): lower it or "
                       "ask the user to raise the hard limit.")
        return BuildSettingsResult(
            done=done, message=msg, project=str(name), path=str(data.get("path") or p["path"]),
            settings=BuildSettings.from_helper(data.get("settings")), changes=changes, suggested=sug,
            suggested_reasons=reasons, open_files_error=data.get("openFilesError"), next_steps=nxt)
