"""App icon: ios_project_icon turns any image into the project's icon (a square 1024×1024 PNG without transparency)
and points xtool.yml's iconPath at it. A dry run (confirm=false) renders a preview PNG and says what would change;
confirm=true writes it. The work happens in the helper's `projects icon` (helper/iosstudio/features/projects/).
Paths come back, never image bytes."""
from __future__ import annotations

import re
from typing import Annotated, Literal

from mcp.server.mcpserver import Context, MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from pydantic import Field

from .. import helper
from ..backends.projects import resolve_project
from ..core import budget as B
from ..core.errors import rehint
from ..core.params import MaxBytes, ProjectPath
from ..core.registry import tool
from ..models import Out
from ..state import get_state

TIMEOUT = 25            # a big source image re-runs under the daemon's Python (Pillow); call_budget caps it anyway
WARNINGS_CAP = 10
FINDINGS_CAP = 10
TEXT_CUT = 300

Fit = Literal["auto", "fill", "fit"]
_HEX = re.compile(r"#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})")

# The helper's error codes -> the next step for an agent (replaces the helper's app-facing fix).
HINTS: dict[str, str] = {
    "no-image": "Pass image_path of an existing image file (PNG, JPEG, WebP, HEIC, GIF, BMP, TIFF or SVG).",
    "bad-image": "The file isn't an image iOS Studio can read: pass a PNG or JPEG instead.",
    "too-large": "The image is over 50 MB or 100 megapixels: pass a smaller export of it.",
    "bad-color": "Pass background as a hex color like '#ffffff' or '#1e90ff'.",
    "generated-yml": "This project's xtool.yml is generated by a script, so iconPath can't be set here: ask the "
                     "user to add iconPath to the script that writes xtool.yml (ios_project_info shows it).",
    "no-image-tool": "Neither Pillow (in the device service's Python) nor ImageMagick was found: ask the user to "
                     "finish Setup in the app (ios_open_app(page='setup')).",
    "usage": "Check project_path and image_path, then retry.",
}


class IconSource(Out):
    path: str
    width: int | None = None
    height: int | None = None
    format: str | None = Field(None, description="e.g. PNG, JPEG, WEBP")
    has_alpha: bool = Field(False, description="The source has transparency (flattened onto background)")


class IconFinding(Out):
    severity: str = "warning"
    message: str
    hint: str | None = None


class IconResult(B.Budgeted, Out):
    done: bool = Field(description="True when the icon was written (confirm=true); false for a dry run or demo")
    demo: bool = Field(False, description="Demo mode: canned answer, nothing was read or written")
    message: str
    project: str
    path: str
    preview_path: str | None = Field(None, description="Absolute path of the rendered 1024×1024 PNG: open it to "
                                                       "show the user (it's square; iOS rounds the corners)")
    target: str = Field(description="Icon file relative to the project, e.g. 'Resources/AppIcon.png'")
    target_path: str | None = None
    replaces: bool = Field(False, description="An existing file at target is (would be) overwritten")
    yml: str = Field(description="iconPath in xtool.yml: 'add', 'change' or 'keep'")
    previous_icon: str | None = Field(None, description="iconPath before this call")
    would: list[str] = Field(default_factory=list, description="Dry run: what confirm=true would do")
    source: IconSource | None = None
    fit: str | None = Field(None, description="How the image was placed: 'fill' (cover, center-crop) or 'fit' "
                                              "(whole image on the background, 10% margin)")
    background: str | None = None
    backend: str | None = Field(None, description="pillow or imagemagick")
    warnings: list[str] = Field(default_factory=list)
    check: list[IconFinding] = Field(default_factory=list, description="Icon findings of ios_project_check after "
                                                                       "writing; empty = the icon passes")
    next_steps: list[str] = Field(default_factory=list)


def normalize_color(raw: str) -> str:
    """'#fff', 'FFF', '#FFFFFF' -> '#ffffff'; anything else is a ToolError."""
    m = _HEX.fullmatch((raw or "").strip())
    if not m:
        raise ToolError(f"background must be a hex color like '#ffffff' (got {B.clip(raw, 40)!r}).")
    h = m.group(1).lower()
    return "#" + ("".join(c * 2 for c in h) if len(h) == 3 else h)


def source_image(raw: str) -> str:
    """The absolute path of an existing image file inside the allowed folders (anywhere in demo mode)."""
    if not (raw or "").strip():
        raise ToolError("image_path is required: the image to make the icon from.")
    p = helper.expand(raw)
    if not (helper.inside_home(p) or helper.demo_mode()):
        raise ToolError("image_path must be inside your home folder (or IOSSTUDIO_MCP_ALLOW_PATHS).")
    if not p.exists():
        raise ToolError(f"No file at {helper.tilde(str(p))}.")
    if not p.is_file():
        raise ToolError(f"{helper.tilde(str(p))} is a folder; pass an image file.")
    return str(p)


def _source(d: object, fallback: str) -> IconSource:
    d = d if isinstance(d, dict) else {}
    num = lambda k: d.get(k) if isinstance(d.get(k), int) else None   # noqa: E731
    return IconSource(path=helper.tilde(str(d.get("path") or fallback)) or fallback, width=num("width"),
                      height=num("height"), format=str(d["format"]) if d.get("format") else None,
                      has_alpha=bool(d.get("hasAlpha")))


def _would(target: str, replaces: bool, yml: str, previous: str | None) -> list[str]:
    out = [f"Write the 1024×1024 PNG to {target}" + (" (replaces the file there)." if replaces else " (new file).")]
    if yml == "add":
        out.append(f"Add iconPath: {target} to xtool.yml.")
    elif yml == "change":
        out.append(f"Change iconPath in xtool.yml from {previous} to {target}.")
    return out


def register(mcp: MCPServer) -> None:

    @tool(mcp, "Set the app icon", kind="destructive", idempotent=True)
    async def ios_project_icon(
        ctx: Context,
        project_path: ProjectPath,
        image_path: Annotated[str, Field(description="Source image (PNG, JPEG, WebP, HEIC, SVG, …; absolute or ~/…)")],
        background: Annotated[str, Field(description="Hex color behind transparent parts and the margin: #RRGGBB "
                                                     "(or #RGB)")] = "#ffffff",
        fit: Annotated[Fit, Field(description="fill = cover and center-crop; fit = whole image with a 10% margin; "
                                              "auto = fit for images with transparency (logos), else fill")] = "auto",
        confirm: Annotated[bool, Field(description="false = dry run with a preview; true only after the user "
                                                   "agreed")] = False,
        max_bytes: MaxBytes = None,
    ) -> IconResult:
        """Make the app icon from any image: a 1024×1024 PNG without transparency (iOS rounds the corners
        itself, so the file stays square; keep the main content centered), and set iconPath in xtool.yml.
        confirm=false renders preview_path and lists what would change; show the user, then confirm=true."""
        color = normalize_color(background)
        src = source_image(image_path)
        state = get_state(ctx)
        p = await resolve_project(state, project_path)
        root = str(p.get("path") or "")
        try:
            data = await helper.call("projects", "icon", {"path": root, "image": src, "background": color,
                                                          "fit": fit, "confirm": bool(confirm)}, timeout=TIMEOUT)
        except ToolError as exc:
            raise rehint(exc, HINTS) from None
        data = data if isinstance(data, dict) else {}
        demo = bool(data.get("demo"))
        applied = bool(data.get("applied")) and not demo
        target = str(data.get("target") or "Resources/AppIcon.png")
        replaces = bool(data.get("replaces"))
        yml = str(data.get("yml") or "keep")
        previous = data.get("previous")
        preview = data.get("preview")
        warnings = [B.clip(" ".join(str(w).split()), TEXT_CUT) for w in (data.get("warnings") or [])]
        findings = [IconFinding(severity=str(f.get("severity") or "warning"),
                                message=B.clip(" ".join(str(f.get("message") or "").split()), TEXT_CUT),
                                hint=B.clip(str(f["hint"]), TEXT_CUT) if f.get("hint") else None)
                    for f in (data.get("check") or []) if isinstance(f, dict)]
        cut = max(len(warnings) - WARNINGS_CAP, 0) + max(len(findings) - FINDINGS_CAP, 0)
        would = [] if applied else _would(target, replaces, yml, previous)

        nxt: list[str] = []
        if applied:
            message = f"The icon was written to {target}" + (" and iconPath set in xtool.yml." if yml != "keep"
                                                             else "; xtool.yml already pointed at it.")
            if findings:
                nxt.append("The icon still has problems (see check): fix them or call ios_project_icon again with "
                           "another image.")
            nxt.append("Call ios_project_check to confirm the project config, then ios_run to see the icon on the "
                       "iPhone's Home Screen.")
        else:
            if demo:
                message = "Demo mode: this is a canned preview; nothing was read or written."
            else:
                message = f"Preview rendered at {preview}. Nothing was changed."
            nxt.append("Show the user preview_path (the square file; iOS rounds the corners on the Home Screen) and "
                       "ask whether to use it; only then repeat the call with confirm=true.")
            nxt.append("To frame it differently, call again with fit='fit' (whole image, margin), fit='fill' "
                       "(crop to fill) or another background.")
        model = IconResult(
            done=applied, demo=demo, message=message, project=str(data.get("name") or p.get("name") or root),
            path=str(data.get("path") or root), preview_path=str(preview) if preview else None, target=target,
            target_path=data.get("targetPath"), replaces=replaces, yml=yml,
            previous_icon=str(previous) if previous else None, would=would,
            source=_source(data.get("source"), src), fit=data.get("fit"), background=data.get("background") or color,
            backend=data.get("backend"), warnings=warnings[:WARNINGS_CAP], check=findings[:FINDINGS_CAP],
            next_steps=nxt, truncated=cut > 0, omitted=cut,
            note=f"{cut} more warnings/findings not shown." if cut else None)
        return model.with_budget(max_bytes)
